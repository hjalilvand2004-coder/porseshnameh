import type { IndicatorId } from "./types";

/**
 * شناسنامه عملیاتی سنجش شاخص (Indicator Measurement Charter)
 *
 * برای هر شاخص، یک «شناسنامه عملیاتی» که دقیقاً نُه جزء سند راهنما را پوشش می‌دهد:
 *  ۱) مفهوم اصلی شاخص + چه چیزی خارج از دامنه است
 *  ۲) واحد سنجش و تجمیع
 *  ۳) دوره زمانی
 *  ۴) پرسش‌های واقعه‌محور (رخداد، تداوم، فراوانی، پیامد)
 *  ۵) داده‌های کمی
 *  ۶) شواهد زمینه‌ای و عملکردی
 *  ۷) قواعد تعیین سطح (با «و»/«یا» و تقدم) + لنگرهای مصداقی هر ضریب (شاهد‌محور)
 *  ۸) وضعیت شواهد (منبع، کفایت، تعارض، تأیید)
 *  ۹) موارد استثنایی و مرز شاخص‌ها
 *  + سهم وب‌سرویس‌های سازمان‌های متولی در پرکردن/راستی‌آزمایی شاخص
 *
 * قواعد هر شاخص عیناً با موتور حل قطعی (engine.ts) هم‌راستا نوشته شده‌اند؛
 * مصداق‌ها لنگر تفسیری ارزیاب‌اند، نه قاعده امتیاز جدید.
 */

export interface CharterLevelRule {
  /** برچسب ضریب به ارقام فارسی — «۰»، «۰٫۵»، «۱»، «۰٫۲۵»، «۰٫۷۵» */
  coeff: string;
  /** قاعده احراز — با وصل‌کننده‌های «و»/«یا» و مشخص‌بودن تقدم */
  rule: string;
}

export interface CharterAnchor {
  /** ضریب متناظر قاعده */
  coeff: string;
  /** مصداق/شاهد عینی و ملموس برای یکسان‌سازی تفسیر ارزیابان */
  example: string;
}

export interface CharterServiceInput {
  /** شناسه سرویس متولی — مطابق WEB_SERVICES در legacy-map */
  serviceId: string;
  /** این استعلام دقیقاً چه چیزی برای این شاخص پر یا راستی‌آزمایی می‌کند */
  contribution: string;
}

export interface IndicatorCharter {
  /** ۱) دقیقاً چه محرومیتی سنجیده می‌شود */
  concept: string;
  /** ۱) چه چیزی خارج از دامنه شاخص است */
  outOfScope: string[];
  /** ۲) واحد سنجش */
  unit: string;
  /** ۲) نحوه تبدیل وضعیت اعضا به یک سطح خانوار */
  aggregation: string;
  /** ۳) دوره زمانی سنجش */
  period: string;
  /** ۴) پرسش‌های واقعه‌محور — رخداد/تداوم/فراوانی/پیامد */
  eventQuestions: string[];
  /** شناسه پرسش‌های مرتبط در کاتالوگ (خالی = از پروفایل اعضا/ویرایشگر داده محاسبه می‌شود) */
  questionIds: string[];
  /** ۵) داده‌های کمی مورد نیاز */
  quantitative: string[];
  /** ۶) شواهد زمینه‌ای و عملکردی — اثر بر غذا، درمان، تحصیل، امنیت، مراقبت و زندگی روزمره */
  contextualEvidence: string[];
  /** ۷) قواعد تعیین سطح — شرایط هر ضریب با «و»/«یا» */
  levelRules: CharterLevelRule[];
  /** ۷) قاعده تقدم بین قواعد */
  precedence: string;
  /** ۷) لنگرهای مصداقی (شاهد‌محور) برای هر ضریب */
  anchors: CharterAnchor[];
  /** ۸) وضعیت شواهد — منبع، کفایت، تعارض، تأیید */
  evidenceStatus: string[];
  /** ۹) استثناها، جلوگیری از هم‌پوشانی و موارد نیازمند بررسی تخصصی */
  exceptions: string[];
  /** + سهم وب‌سرویس‌های متولی در این شاخص */
  serviceInputs: CharterServiceInput[];
  /** اگر آستانه‌های شاخص نیازمند تصویب مرجع است */
  pendingApproval?: string;
}
