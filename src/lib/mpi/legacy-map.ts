/** جمع کاربرد وب‌سرویس‌ها برای نمایش در صفحه مهاجرت */
export function serviceFeedLabel(id: IndicatorId): string | undefined {
  const services = WEB_SERVICES.filter((s) => s.feeds.includes(id));
  return services.length ? services.map((s) => s.name.split(" — ")[0]).join("، ") : undefined;
}

export function indicatorLegacyBadge(id: IndicatorId): { short: string; className: string; title: string; old: string } {
  const m = LEGACY_MAP[id];
  const meta = LEGACY_ACTION_META[m.action];
  const old = m.old[0] ?? "—";
  const svc = serviceFeedLabel(id);
  const title = `${meta.label}\nمنبع قبلی: ${m.old.join(" | ")}\n${m.note}${svc ? `\nراستی‌آزمایی ثبتی: ${svc}` : ""}`;
  return { short: meta.short, className: meta.className, title, old };
}

