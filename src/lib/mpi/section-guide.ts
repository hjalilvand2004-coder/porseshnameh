/** خدمات ثبتی مرتبط با یک شاخص (برای نمایش در راهنمای شاخص) */
export function servicesOfIndicator(id: IndicatorId): string[] {
  return WEB_SERVICES.filter((s) => s.feeds.includes(id)).map((s) => s.name);
}

/** ردیف‌های جدول نگاشت یک گام امتیازی */
export function stepMappingRows(stepKey: string): { id: IndicatorId; title: string; action: LegacyAction; old: string[]; note: string }[] {
  return indicatorsOfStep(stepKey).map((id) => ({
    id,
    title: INDICATOR_TITLES[id],
    action: LEGACY_MAP[id].action,
    old: LEGACY_MAP[id].old,
    note: LEGACY_MAP[id].note,
  }));
}

