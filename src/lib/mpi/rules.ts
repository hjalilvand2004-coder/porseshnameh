/** ضرایب مجاز — سه‌حالته و پنج‌حالته */
export const SCALE_THREE = [0, 0.5, 1] as const;
export const SCALE_FIVE = [0, 0.25, 0.5, 0.75, 1] as const;

/** شاخص‌های پنج‌حالته نسخه حاضر */
export const FIVE_STATE: IndicatorId[] = ["A6", "C4", "C8", "D3"];

export function scaleOf(id: IndicatorId): readonly number[] {
  return FIVE_STATE.includes(id) ? SCALE_FIVE : SCALE_THREE;
}

/** اعتبارسنجی ضریب نسبت به مقیاس مجاز — خارج از مقیاس پذیرفته نمی‌شود */
export function coeffAllowed(id: IndicatorId, coeff: number): boolean {
  return scaleOf(id).includes(coeff);
}

